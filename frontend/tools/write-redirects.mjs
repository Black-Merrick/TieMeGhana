/**
 * Write dist/_redirects from the environment, after the bundle is built.
 *
 * Netlify takes redirect rules from two places: `netlify.toml`, which is
 * parsed statically and does **not** substitute environment variables, and a
 * plain `_redirects` file in the publish directory, which is read after the
 * build and can therefore be generated.
 *
 * That difference is the whole reason this script exists. Putting the rules in
 * `netlify.toml` meant the backend's address was committed into the repository
 * and moving the backend meant editing a file and pushing. Generating them
 * means the address is one environment variable in the Netlify dashboard, set
 * in the same place as every other deployment setting, and changed by
 * redeploying rather than by a commit.
 *
 * Proxying rather than calling the backend across origins keeps the browser
 * seeing a single origin: no CORS preflight on every request, no second origin
 * to keep in Django's settings, and no backend URL compiled into the bundle.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const DIST = resolve(import.meta.dirname, "..", "dist", "_redirects");

/** Where the Django service lives. Set this in the Netlify dashboard. */
const target = (process.env.API_PROXY_TARGET ?? "").trim().replace(/\/+$/, "");

const lines = [
  "# Generated by tools/write-redirects.mjs. Do not edit: it is rewritten on",
  "# every build. The backend address comes from API_PROXY_TARGET.",
  "",
];

if (target) {
  lines.push(
    "# The API, the Django admin used to approve clips, and the admin's own",
    "# stylesheets. Proxied so the browser sees one origin.",
    `/api/*    ${target}/api/:splat    200`,
    `/admin/*  ${target}/admin/:splat  200`,
    `/static/* ${target}/static/:splat 200`,
    "",
  );
} else {
  // A build with no backend configured still has to produce a working site,
  // because that is what `npm run build` does on a laptop and in CI. Said out
  // loud rather than silently omitted: a deploy missing this variable would
  // otherwise look fine until the first request failed.
  console.warn(
    "\n  API_PROXY_TARGET is not set, so the built site has no API proxy.",
    "\n  That is expected locally. On Netlify, set it to the Render service's",
    "\n  address, for example https://tiemeghana-api.onrender.com\n",
  );
  lines.push("# No API proxy: API_PROXY_TARGET was not set at build time.", "");
}

// Last, and it must stay last: the first matching rule wins, so a fallback
// placed above the proxy rules would swallow every API call and answer it with
// the app's own index.html.
lines.push(
  "# Single page app fallback. A prescription QR code points at",
  "# /p/<reference>, which is not a file on disk.",
  "/*  /index.html  200",
  "",
);

mkdirSync(dirname(DIST), { recursive: true });
writeFileSync(DIST, lines.join("\n"), "utf8");

console.log(
  target
    ? `  wrote dist/_redirects, proxying /api to ${target}`
    : "  wrote dist/_redirects with no API proxy",
);
